// What the browser can tell the server about this visit. It is the same picture any
// analytics product builds: device and browser, screen and connection, locale, where the
// visit came from, and how fast the page loaded. No fingerprinting, nothing from gameplay.
function deviceReport(extra = {}) {
  const w = innerWidth;
  const conn = navigator.connection || {};
  const nav = /** @type {any} */ (navigator);
  const params = new URLSearchParams(location.search);
  const nav0 = performance.getEntriesByType('navigation')[0] || {};
  return {
    vid: visitorId,
    name: prefs.name || null,
    screen: w < 480 ? 'phone' : w < 900 ? 'tablet' : w < 1500 ? 'laptop' : 'large',
    resolution: `${screen.width}x${screen.height}`,
    viewport: `${w}x${innerHeight}`,
    orientation: w >= innerHeight ? 'landscape' : 'portrait',
    colorDepth: screen.colorDepth || null,
    dpr: Math.round((devicePixelRatio || 1) * 100) / 100,
    cores: nav.hardwareConcurrency || null,
    memoryGb: nav.deviceMemory || null,
    network: conn.effectiveType || null,
    downlinkMbps: conn.downlink || null,
    saveData: Boolean(conn.saveData),
    touch: (navigator.maxTouchPoints || 0) > 0,
    maxTouch: navigator.maxTouchPoints || 0,
    theme: matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark',
    reducedMotion: matchMedia('(prefers-reduced-motion: reduce)').matches,
    installed: matchMedia('(display-mode: standalone)').matches || navigator.standalone === true,
    tz: Intl.DateTimeFormat().resolvedOptions().timeZone,
    langs: (navigator.languages || []).slice(0, 3).join(','),
    // Campaign parameters, the way every analytics tool reads them.
    utmSource: params.get('utm_source'),
    utmMedium: params.get('utm_medium'),
    utmCampaign: params.get('utm_campaign'),
    // Someone arriving on an invite link is a very different visitor from someone
    // who found the home page, so it is worth telling apart.
    viaInvite: params.has('join'),
    entry: location.pathname,
    loadMs: Math.round(nav0.duration || performance.now()),
    ttfbMs: Math.round(nav0.responseStart || 0) || null,
    domReadyMs: Math.round(nav0.domContentLoadedEventEnd || 0) || null,
    automated: Boolean(navigator.webdriver),
    ...extra,
  };
}

