function emit(event, payload = {}) {
  return new Promise((resolve) => {
    // Fail fast rather than leaving a button hanging when the socket is down.
    if (!socket.connected) {
      const error = 'Not connected to the game server. Reconnecting, try again in a moment.';
      toast(error, 'error');
      return resolve({ ok: false, error });
    }
    let done = false;
    const timer = setTimeout(() => { if (!done) { done = true; resolve({ ok: false, error: 'No response from server, check your connection.' }); } }, 8_000);
    socket.emit(event, payload, (res) => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      if (res && res.ok === false && res.error) toast(res.error, 'error');
      resolve(res || { ok: true });
    });
  });
}

socket.on('connect', () => {
  const wasOffline = !store.connected;
  store.connected = true;
  $('#conn-overlay')?.remove();
  if (wasOffline && !store.snap) render();
  const savedRoom = sessionStorage.getItem('gn_room');
  if (savedRoom) {
    emit('room:join', { code: savedRoom, name: prefs.name, avatar: prefs.avatar, ...identity }).then((res) => {
      if (!res.ok) {
        sessionStorage.removeItem('gn_room');
        store.snap = null;
        render();
      }
    });
  }
});

socket.on('disconnect', () => {
  store.connected = false;
  if (store.snap) showConnOverlay();
  else render();
});

socket.on('connect_error', () => {
  if (store.connected) { store.connected = false; if (!store.snap) render(); }
});

socket.on('room:state', (snap) => {
  const prevPhase = currentPhase(store.snap);
  // A fresh game (or a new island round) gets its entrance animations back.
  const prevRound = store.snap?.blendin?.round ?? store.snap?.island?.roundNum;
  const nextRound = snap.blendin?.round ?? snap.island?.roundNum;
  if (store.snap && (store.snap.game !== snap.game || (prevRound != null && nextRound != null && nextRound !== prevRound))) {
    resetAnims();
  }
  store.snap = snap;
  store.everJoined = true;
  sessionStorage.setItem('gn_room', snap.code);
  const newPhase = currentPhase(snap);
  if (prevPhase !== newPhase) closeModal();
  render();
});

socket.on('room:kicked', () => {
  leaveLocal();
  toast('You were removed from the room by the owner.', 'error', 4000);
  render();
});

socket.on('room:takenover', () => {
  // Keep the room code in sessionStorage so reloading rejoins the game instead of
  // dropping the player back on the landing page.
  store.snap = null;
  openModal(h('div', { style: 'text-align:center' },
    h('div', { class: 'modal-title', style: 'justify-content:center' }, '👋 Session moved'),
    h('p', { class: 'hint' }, `You opened ${BRAND.short} in another tab. This one has been disconnected.`),
    h('button', { class: 'btn btn-primary btn-block', style: 'margin-top:14px', onClick: () => { closeModal(); location.reload(); } }, 'Play in this tab instead'),
  ), { dismissible: false });
});

function leaveLocal() {
  store.snap = null;
  sessionStorage.removeItem('gn_room');
}

function currentPhase(snap) {
  if (!snap) return null;
  return `${snap.game}:${snap.blendin?.phase || snap.island?.phase || snap.silentorder?.phase
    || snap.swaporstay?.phase || snap.sleepless?.phase || 'lobby'}`;
}

