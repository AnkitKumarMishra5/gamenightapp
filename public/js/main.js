async function shareInvite(code) {
  const url = `${location.origin}/?join=${code}`;
  const title = `${BRAND.short}. Room ${code}`;
  const text = INVITE_MESSAGES[(Math.random() * INVITE_MESSAGES.length) | 0](code);
  if (navigator.share) {
    try {
      await navigator.share({ title, text, url });
      return;
    } catch (err) {
      if (err?.name === 'AbortError') return; // user dismissed the sheet
    }
  }
  try {
    await navigator.clipboard.writeText(`${text}\n${url}`);
    toast('Invite copied. Paste it to your friends 📤', 'success');
  } catch {
    openModal(h('div', {},
      h('div', { class: 'modal-title' }, '📤 Invite your friends'),
      h('p', { class: 'hint', style: 'margin-bottom:12px' }, 'Share this code or link. Anyone with it can join your room.'),
      h('div', { class: 'share-code' }, code),
      h('p', { class: 'hint', style: 'margin-top:10px; word-break:break-all' }, url),
      h('button', { class: 'btn btn-primary btn-block', style: 'margin-top:14px', onClick: closeModal }, 'Done'),
    ));
  }
}

// Two exits, easy to confuse: one puts the table back in the lobby with the room
// intact, the other takes you out of the room altogether.
function leaveRoom() {
  const isHost = store.snap?.you?.isHost;
  const s = store.snap;
  const inGame = Boolean(s?.blendin || s?.island || s?.silentorder || s?.swaporstay || s?.sleepless);
  const canEndGame = inGame && isHost;

  const quit = async () => {
    await emit('room:leave');
    leaveLocal();
    landingStep = 2;
    joinOpen = false;
    toast('You left the room. 👋');
    render();
  };

  openModal(h('div', { style: 'text-align:center' },
    h('div', { class: 'modal-title', style: 'justify-content:center' }, 'Leaving?'),
    // Only the owner hands the room on, so only the owner needs the warning.
    isHost && h('p', { class: 'hint' },
      'Leaving the room hands it to another player, and it closes once the last player leaves.'),
    h('div', { style: 'display:grid; gap:10px; margin-top:16px' },
      canEndGame && h('button', {
        class: 'btn btn-primary',
        onClick: async (e) => {
          e.currentTarget.disabled = true;
          const res = await emit('room:backToLobby');
          if (!res.ok) { e.currentTarget.disabled = false; toast(res.error, 'error'); return; }
          closeModal();
          toast('Back in the lobby. 🏠');
        },
      }, '🏠 Leave the game, stay in the room'),
      inGame && !isHost && h('p', { class: 'hint' },
        'Only the room owner can end the game and take everyone back to the lobby.'),
      h('button', { class: 'btn btn-danger', onClick: () => { closeModal(); quit(); } }, '🚪 Leave the room'),
      h('button', { class: 'btn btn-ghost', onClick: closeModal }, 'Stay'),
    ),
  ));
}

