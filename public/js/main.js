// The server lists whatever is in public/media (see `npm run backdrop`). Images hold for
// a while and cross-fade; a video plays all the way through and then hands over. Two
// layers swap between them so nothing ever flashes to black mid-transition.
const BACKDROP_IMAGE_MS = 11_000;
const BACKDROP_FADE_MS = 1600;

(function loadBackdrop() {
  const scene = $('.bg-scene');
  const videoEl = document.getElementById('bg-video');
  if (!scene) return;

  const bail = () => videoEl?.remove();

  // "Reduce motion" is a request to stop things moving, not to strip the artwork out. A
  // still photograph is not motion, so it stays: one image, no cross-fade, no rotation
  // timer, and no video. Removing the backdrop entirely was the old behaviour and it left
  // anyone with the accessibility setting on looking at a bare gradient.
  const stillOnly = matchMedia('(prefers-reduced-motion: reduce)').matches;

  // Data saver and 2G are about bytes, so those genuinely do skip the download.
  const conn = navigator.connection;
  if (conn?.saveData || /2g/.test(conn?.effectiveType || '')) return bail();

  fetch('/api/backdrop')
    .then((res) => res.json())
    .then(({ items }) => {
      if (!items?.length) return bail();
      videoEl?.remove();          // we manage our own elements from here
      document.body.classList.add('has-bg-media');
      if (items.some((i) => i.people)) document.body.classList.add('has-people-media');

      if (stillOnly) {
        const still = items.find((i) => i.kind === 'image') || items[0];
        if (still?.kind === 'image') showStill(scene, still);
        return;
      }
      startRotation(scene, items);
    })
    .catch(bail);
})();

// One image, held indefinitely. Used when the visitor has asked for reduced motion.
function showStill(scene, item) {
  const el = h('div', { class: 'bg-layer', 'aria-hidden': 'true' });
  scene.prepend(el);
  const img = new Image();
  img.onload = () => {
    el.style.backgroundImage = `url("${item.src}")`;
    el.classList.add('ready');
  };
  img.onerror = () => el.remove();
  img.src = item.src;
}

function startRotation(scene, items) {
  // Two stacked layers: one visible, one being prepared underneath.
  const layers = [makeLayer(), makeLayer()];
  layers.forEach((l) => scene.prepend(l.el));
  let front = 0;
  let index = -1;
  let timer = null;

  function makeLayer() {
    const el = h('div', { class: 'bg-layer', 'aria-hidden': 'true' });
    const video = h('video', { class: 'bg-layer-video', muted: true, playsinline: true, preload: 'auto' });
    video.muted = true;                    // attribute alone is not enough on iOS
    el.append(video);
    return { el, video };
  }

  function show(i) {
    clearTimeout(timer);
    index = i % items.length;
    const item = items[index];
    const back = layers[1 - front];

    const reveal = () => {
      back.el.classList.add('ready');
      layers[front].el.classList.remove('ready');
      front = 1 - front;
      // Let the outgoing layer finish fading before we reuse it.
      setTimeout(() => {
        const stale = layers[1 - front];
        stale.video.pause();
        stale.video.removeAttribute('src');
        stale.video.load();
        stale.el.style.backgroundImage = '';
      }, BACKDROP_FADE_MS);
    };

    if (item.kind === 'video') {
      back.el.style.backgroundImage = '';
      back.el.classList.add('is-video');
      back.video.src = item.src;
      back.video.currentTime = 0;
      // Advance when the clip finishes rather than on a timer, so it plays in full.
      back.video.onended = () => show(index + 1);
      back.video.onerror = () => show(index + 1);
      back.video.play().then(reveal).catch(() => {
        // Autoplay refused (rare for muted video) — skip rather than sit on a black frame.
        show(index + 1);
      });
      // Safety net: if the clip stalls, move on at twice its expected length.
      const guard = (back.video.duration || 12) * 2000;
      timer = setTimeout(() => show(index + 1), Number.isFinite(guard) ? guard : 24_000);
      return;
    }

    back.el.classList.remove('is-video');
    const img = new Image();
    img.onload = () => {
      back.el.style.backgroundImage = `url("${item.src}")`;
      reveal();
      timer = setTimeout(() => show(index + 1), BACKDROP_IMAGE_MS);
    };
    img.onerror = () => show(index + 1);
    img.src = item.src;
  }

  show(0);

  // Pause the rotation while the tab is hidden; nobody is watching, and a background
  // video keeps decoding otherwise.
  document.addEventListener('visibilitychange', () => {
    const current = layers[front];
    if (document.hidden) {
      clearTimeout(timer);
      current.video.pause();
    } else if (current.el.classList.contains('is-video')) {
      current.video.play().catch(() => {});
    } else {
      timer = setTimeout(() => show(index + 1), BACKDROP_IMAGE_MS);
    }
  });
}

