// ---------- fx ----------
socket.on('fx', (fx) => {
  const mine = fx.playerId === identity.playerId;
  switch (fx.kind) {
    // ---- shared ----
    case 'bi-dealing': memes.suspense(); break;
    case 'game-start': memes.yeet(); setTimeout(() => memes.drumroll(), 320); break;

    // ---- Blend In ----
    case 'clue': if (!mine) sound.pop(); break;
    case 'reaction': {
      if (fx.added) {
        // Seeded: the whole room hears the same clip, and a fresh reaction cuts the
        // previous one short rather than being skipped.
        playReaction(fx.emoji, fx.seed);
        // And everyone sees who it came from: the emoji floats up out of their tile.
        const tile = document.querySelector(`[data-pid="${CSS.escape(fx.playerId)}"]`);
        if (tile) {
          const float = h('span', { class: 'react-float' }, fx.emoji);
          tile.style.position = 'relative';
          tile.append(float);
          setTimeout(() => float.remove(), 2600);
        }
      }
      break;
    }
    case 'bi-autovote': {
      // The table hears the round close: three beats, then the vote screen arrives.
      let n = fx.seconds || 3;
      toast(`🗳️ Everyone has spoken. Voting in ${n}…`);
      const tick = setInterval(() => {
        n -= 1;
        if (n <= 0) { clearInterval(tick); return; }
        toast(`🗳️ Voting in ${n}…`);
        sound.tick();
      }, 1000);
      break;
    }
    case 'vote-start': memes.suspense(); break;
    case 'vote-cast': sound.tick(); break;
    // Sleepless: night and vote progress deliberately carry no playerId, so these tick
    // for everyone. Naming who moved would be a tell.
    case 'sl-tuck': sound.tick(); break;
    case 'sl-vote': sound.tick(); break;
    case 'room-react': {
      // A live-stream style float: the emoji and its sender rise from the foot of the
      // screen on every phone in the room, wherever each of them happens to be looking.
      playReaction(fx.emoji, fx.seed);
      const who = store.snap?.players.find((p) => p.id === fx.playerId);
      const float = h('div', { class: 'gn-react-float', style: `left:${(8 + Math.random() * 60).toFixed(0)}%` },
        h('span', { class: 'grf-emoji' }, fx.emoji),
        who && h('span', { class: 'grf-name' }, `${who.avatar} ${who.name}`));
      document.body.append(float);
      setTimeout(() => float.remove(), 2800);
      break;
    }
    case 'ss-react': {
      // Same shared-clip rule as Blend In's reactions, landing over the chair at the
      // card table instead of a player tile.
      playReaction(fx.emoji, fx.seed);
      const chair = document.querySelector(`.ct-who[data-id="${CSS.escape(fx.playerId)}"]`);
      if (chair) {
        const float = h('span', { class: 'react-float' }, fx.emoji);
        chair.append(float);
        setTimeout(() => float.remove(), 2600);
      }
      break;
    }
    case 'ss-left': {
      const who = store.snap?.players.find((p) => p.id === fx.playerId);
      toast(`${who?.name || 'Someone'} left the table. Their card goes back to the deck.`, 'info');
      break;
    }
    case 'vote-tie': {
      memes.crickets();
      if (fx.quip) { setTimeout(() => playMeme('rimshot'), 700); toast(fx.quip); }
      break;
    }
    case 'no-elimination': memes.crickets(); break;
    case 'elimination': {
      memes.drumroll();
      setTimeout(() => {
        playMeme('boom');
        // An innocent going out deserves a groan; catching an impostor deserves a gasp.
        if (fx.role === 'insider') { memes.gasp(); setTimeout(() => memes.boo(), 420); }
        else memes.gasp();
      }, 1250);
      break;
    }
    case 'white-guess': {
      if (fx.correct) { playMeme('airhorn'); setTimeout(() => playMeme('applause'), 500); }
      else playMeme('sadTrombone');
      break;
    }
    case 'game-over': {
      // Each ending owns a long signature stinger, so a win SOUNDS like whose win it was:
      // triumphant fanfare with a dhol under it for the insiders, a sly villain theme for
      // the outsiders who fooled the whole table.
      if (fx.winner === 'insiders') { playMeme('winInsiders'); setTimeout(() => playMeme('dhol'), 500); }
      else { playMeme('winOutsiders'); setTimeout(() => playMeme('airhorn'), 1400); }
      confettiRain(2400);
      break;
    }

    // ---- The Island ----
    case 'island-open': memes.sparkle(); break;
    case 'island-hint': {
      memes.coin();
      const who = store.snap?.players.find((p) => p.id === fx.playerId);
      toast(`💡 ${who ? `${who.name} asked` : 'Asked'} for a hint: ${fx.items.join(' and ')} can come aboard.`, 'info', 4200);
      break;
    }
    case 'island-attempt': if (!mine) sound.pop(); break;
    case 'island-item': {
      if (fx.fits) { playMeme('ding'); }
      else { memes.bonk(); }
      break;
    }
    case 'island-solved': {
      playMeme('wow');
      setTimeout(() => playMeme('kaching'), 500);
      confettiBurst({ count: 110 });
      break;
    }
    case 'island-wrong-pattern': {
      memes.buzzer();
      if (mine && fx.guessesLeft != null) {
        toast(fx.guessesLeft === 1
          ? 'Not it. One guess left! 😬'
          : `Not it, ${fx.guessesLeft} guesses left.`, 'error');
      }
      break;
    }
    case 'island-knocked-out': {
      playMeme('fail');
      const who = store.snap?.players.find((p) => p.id === fx.playerId);
      toast(mine
        ? 'Three wrong guesses. You\'re out for this round 💀'
        : `${who?.name || 'Someone'} used all three guesses and is out 💀`, 'error', 4000);
      break;
    }
    case 'island-over': memes.applause(); confettiRain(1800); break;

    // ---- errors ----
    case 'ai-error': memes.recordScratch(); if (fx.message) toast(fx.message, 'error'); break;
    case 'item-invalid': {
      memes.recordScratch();
      setTimeout(() => playMeme('bruh'), 380);
      if (fx.message) toast(fx.message, 'error', 4000);
      break;
    }
  }
});

