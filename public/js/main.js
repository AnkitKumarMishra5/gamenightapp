// High-entropy client hints give the real OS version and, on Android, the device model.
// It is an explicit opt-in API, so nothing is read unless the browser offers it.
if (navigator.userAgentData?.getHighEntropyValues) {
  navigator.userAgentData
    .getHighEntropyValues(['platformVersion', 'model', 'architecture', 'uaFullVersion'])
    .then((hints) => {
      hintsSent = true;
      fetch('/api/hello', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(deviceReport({
          platformVersion: hints.platformVersion || null,
          model: hints.model || null,
          arch: hints.architecture || null,
        })),
      }).catch(() => {});
    })
    .catch(() => { if (!hintsSent) sendHello(); });
} else {
  sendHello();
}
let hintsSent = false;

// How long the visit lasted, sent once when the tab goes away. sendBeacon is the only
// thing browsers reliably deliver at that moment.
let leftReported = false;
addEventListener('visibilitychange', () => {
  if (document.visibilityState !== 'hidden' || leftReported) return;
  leftReported = true;
  const body = JSON.stringify({
    vid: visitorId,
    name: prefs.name || null,
    seconds: Math.round(performance.now() / 1000),
    installed: matchMedia('(display-mode: standalone)').matches,
  });
  navigator.sendBeacon?.('/api/bye', new Blob([body], { type: 'application/json' }));
});


// Sound is ON by default, but every browser blocks audio until the page has been
// interacted with once ("sticky activation") — there is no way around that, so we listen
// for every event type that counts and start the moment one arrives.
let audioArmed = false;
function armAudioFromGesture() {
  if (audioArmed) return;
  audioArmed = true;
  clearTimeout(soundHintTimer);
  $('#sound-hint')?.remove();
  // A short flourish first, then the groove fades in underneath it.
  playWelcome({ thenStartMusic: !store.snap });
  armAmbience();
  if (!store.snap) startAmbience();
}
for (const evt of ['pointerdown', 'pointerup', 'click', 'keydown', 'touchstart', 'touchend']) {
  addEventListener(evt, armAudioFromGesture, { passive: true });
}

// If they have not touched anything after a moment, say why it is quiet rather than
// leaving them to wonder whether the sound is broken.
