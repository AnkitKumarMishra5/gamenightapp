// Must match roomCode()'s alphabet in server/lib/util.js (no O/0, no I/1).
const CODE_CHARS = 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
const CODE_RE = new RegExp(`[${CODE_CHARS}]{5}`, 'g');

// Pull a room code out of anything a friend might paste: the bare code, a join link, or
// the whole invite message. Returns null when there is nothing code-shaped in it.
function extractRoomCode(raw) {
  const text = String(raw || '').trim();
  if (!text) return null;

  // 1. A join link is unambiguous, so trust it first.
  const fromLink = text.match(/[?&]join=([A-Za-z0-9]{5})\b/i);
  if (fromLink) return fromLink[1].toUpperCase();

  // 2. "Room code: XXXXX" — the wording our own invite uses.
  const labelled = text.match(/(?:room\s*code|code)\s*[:\-]?\s*([A-Za-z0-9]{5})\b/i);
  if (labelled) {
    const candidate = labelled[1].toUpperCase();
    if ([...candidate].every((c) => CODE_CHARS.includes(c))) return candidate;
  }

  // 3. Already just a code.
  const bare = text.toUpperCase().replace(/[^A-Z0-9]/g, '');
  if (bare.length === 5 && [...bare].every((c) => CODE_CHARS.includes(c))) return bare;

  // 4. Last resort: the only code-shaped token in the text, ignoring ordinary words.
  const matches = text.toUpperCase().match(CODE_RE) || [];
  const plausible = matches.filter((m) => /[2-9]/.test(m) || !/^[A-Z]+$/.test(m));
  if (plausible.length === 1) return plausible[0];
  if (matches.length === 1) return matches[0];
  return null;
}

